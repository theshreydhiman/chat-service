import { z } from 'zod';

export const MESSAGE_TYPES = [
  'TEXT',
  'IMAGE',
  'VIDEO',
  'DOCUMENT',
  'ENQUIRY',
  'OFFER',
  'INFO',
  'CONFIRMATION',
] as const;

export type MessageType = (typeof MESSAGE_TYPES)[number];

export const attachmentSchema = z.object({
  key: z.string().min(1),
  mime: z.string(),
  size: z.number().int().positive(),
  name: z.string().optional(),
});

export type Attachment = z.infer<typeof attachmentSchema>;

// What a client may send. Ids, sender and timestamps are assigned by the server.
export const sendMessageSchema = z.object({
  conversation_id: z.string(),
  // Generated by the client per message and reused on retry, so a resend after
  // a timeout or send_error can't produce a second copy.
  client_ref: z.string().uuid(),
  type: z.enum(['TEXT', 'IMAGE', 'VIDEO', 'DOCUMENT']),
  message: z.string().max(4000).default(''),
  attachments: z.array(attachmentSchema).max(10).default([]),
});

export type SendMessageInput = z.infer<typeof sendMessageSchema>;

export interface ChatMessage {
  conversation_id: string;
  message_id: string;
  sender_id: string;
  recipient_id: string;
  type: MessageType;
  message: string;
  attachments: Attachment[];
  metadata?: Record<string, unknown>;
  created_at: string;
}

export interface ConversationRow {
  user_id: string;
  conversation_id: string;
  other_user_id: string;
  last_message?: string;
  last_message_id?: string;
  last_message_at?: string;
  last_sender_id?: string;
  last_read_message_id?: string;
  unread_count: number;
  created_at: string;
}

export interface Page<T> {
  items: T[];
  cursor?: string;
}
